import { expect, test } from "@playwright/test";
import { existsSync, mkdirSync, readFileSync, readdirSync } from "node:fs";
import { basename, resolve } from "node:path";
import { mount, openActive, started } from "./fixtures";
const artifacts=".visual-qa/distance-precision";
for(const width of [320,360,390])for(const [meters,display] of [[86239,"86.2 KM"],[86000,"86.0 KM"]] as const)test(`${meters}m keeps ${display} on all surfaces at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:844});await page.emulateMedia({reducedMotion:"reduce"});
 const latitude=40+meters/6371000*180/Math.PI;
 let payload:unknown;
 page.on("request",request=>{if(request.method()==="POST"&&request.url().endsWith("/quest-runs/r/check-in"))payload=request.postDataJSON();});
 const {counters}=await mount(page,{run:started,latitude,longitude:44,accuracy:11,checkError:"You are outside the checkpoint radius",questContent:{title:"Blue Mosque",latitude:40,longitude:44,radius_m:100}});await openActive(page);
 await page.getByRole("button",{name:"CHECK IN",exact:true}).click();
 await expect(page.getByRole("alert")).toContainText(`Your location was about ${display.toLowerCase()} away.`);
 await expect(page.locator(".outside-distance strong")).toHaveText(display);await expect(page.locator(".outside-distance span")).toHaveText("FROM CHECKPOINT");
 await expect(page.getByRole("group",{name:"GPS accuracy from last explicit check-in sample"})).toHaveText("±11 MGPS SAMPLE");
 expect(payload).toEqual({latitude,longitude:44,horizontal_accuracy:11});
 const card=await page.locator(".outside-distance strong").evaluate(el=>{const range=document.createRange();range.selectNodeContents(el);const r=range.getBoundingClientRect(),b=el.getBoundingClientRect();return{lines:range.getClientRects().length,left:r.left,right:r.right,containerLeft:b.left,containerRight:b.right};});
 expect(card.lines).toBe(1);expect(card.left).toBeGreaterThanOrEqual(card.containerLeft);expect(card.right).toBeLessThanOrEqual(card.containerRight);
 mkdirSync(artifacts,{recursive:true});await page.screenshot({path:`${artifacts}/${width}-${meters}-result.png`});
 const before={...counters};await page.getByRole("button",{name:"Close check-in result"}).click();
 await expect(page.getByRole("dialog")).toHaveCount(0);await expect(page.getByRole("button",{name:"CHECK IN",exact:true})).toBeFocused();
 await expect(page.locator(".off-map-distance")).toHaveText(display);
 await expect(page.locator(".last-fix-accuracy")).toHaveText("±11 M");
 await expect(page.locator(".last-fix > span")).toHaveText(`LAST CHECK-IN · ${display} FROM CHECKPOINT`);
 await expect(page.locator(".zone-map-canvas > svg")).toHaveAttribute("aria-label",new RegExp(`Last check-in was ${display.replace('.','\\.')} from the checkpoint`));
 const label=(await page.locator(".off-map-distance").boundingBox())!,zone=(await page.locator(".zone-boundary").boundingBox())!,map=(await page.locator(".zone-map-canvas").boundingBox())!;
 expect(label.x).toBeGreaterThanOrEqual(map.x);expect(label.x+label.width).toBeLessThan(zone.x);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await expect(page.getByText("QUEST ACTIVE",{exact:true})).toBeVisible();
 expect(counters).toEqual(before);expect(counters.gps).toBe(1);expect(counters.checkins).toBe(1);expect(counters.starts).toBe(0);
 await page.screenshot({path:`${artifacts}/${width}-${meters}-map.png`});
});

test("production artifact hides development coordinates even if config enables development GPS",async({page,baseURL})=>{
 test.skip(!existsSync(resolve("dist/index.html")),"Run npm run build before checking the production artifact");
 // Serve the existing build through intercepted requests: no preview/Vite/backend process is started.
 const index=readFileSync(resolve("dist/index.html"),"utf8");
 const scripts=readdirSync(resolve("dist/assets")).filter(name=>name.endsWith(".js"));
 expect(scripts.length).toBeGreaterThan(0);
 for(const file of scripts)expect(readFileSync(resolve("dist/assets",file),"utf8")).not.toMatch(/Development coordinates|CHECK IN WITH DEV COORDINATES/);
 expect(baseURL).toBeTruthy();
 const origin=new URL(baseURL!).origin;
 let documentsServed=0,enabledConfigRequests=0;
 const scriptsServed=new Set<string>();
 const entryScripts=scripts.filter(file=>index.includes(`/assets/${file}`));
 expect(entryScripts.length).toBeGreaterThan(0);
 await page.route(`${origin}/`,route=>{documentsServed++;return route.fulfill({contentType:"text/html",body:index});});
 await page.route(`${origin}/assets/**`,route=>{const name=basename(new URL(route.request().url()).pathname);if(name.endsWith(".js"))scriptsServed.add(name);return route.fulfill({path:resolve("dist/assets",name),contentType:name.endsWith(".css")?"text/css":"application/javascript"});});
 const {counters}=await mount(page,{run:started});
 await page.route("**/api/v1/config",route=>{enabledConfigRequests++;return route.fulfill({json:{development_gps_enabled:true}});});
 await page.reload();await openActive(page);
 expect(documentsServed).toBe(2);
 for(const file of entryScripts)expect(scriptsServed.has(file)).toBe(true);
 expect(enabledConfigRequests).toBe(1);
 await test.info().attach("production-interception",{contentType:"application/json",body:JSON.stringify({origin,documentsServed,entryScripts,scriptsServed:[...scriptsServed],enabledConfigRequests})});
 await expect(page.getByText("QUEST ACTIVE",{exact:true})).toBeVisible();
 await expect(page.getByText("Development coordinates",{exact:true})).toHaveCount(0);
 await expect(page.getByRole("button",{name:"CHECK IN WITH DEV COORDINATES"})).toHaveCount(0);
 expect(counters.gps).toBe(0);expect(counters.checkins).toBe(0);expect(counters.starts).toBe(0);
});
